"""Our from-scratch BPE, loaded with GPT-2's published files, must reproduce
GPT-2's token ids exactly (reference ids generated by tiktoken)."""

import json
from pathlib import Path

import pytest

from toklab.bpe import ByteLevelBPE

ROOT = Path(__file__).resolve().parent.parent
GPT2 = ROOT / "data" / "gpt2"
CASES = json.loads((ROOT / "tests" / "fixtures" / "gpt2_expected.json").read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def gpt2():
    return ByteLevelBPE.from_gpt2_files(GPT2 / "encoder.json", GPT2 / "vocab.bpe")


def test_vocab_size(gpt2):
    assert gpt2.vocab_size == 50257
    assert len(gpt2.merges) == 50000
    assert gpt2.special_tokens == {"<|endoftext|>": 50256}


@pytest.mark.parametrize("case", CASES, ids=lambda c: c["text"][:30] or "<empty>")
def test_matches_reference_ids(gpt2, case):
    assert gpt2.encode(case["text"]) == case["ids"]
    assert gpt2.decode(case["ids"]) == case["text"]


def test_against_tiktoken_on_corpus(gpt2):
    tiktoken = pytest.importorskip("tiktoken")
    enc = tiktoken.get_encoding("gpt2")
    text = (ROOT / "data" / "corpus.txt").read_text(encoding="utf-8")
    assert gpt2.encode(text) == enc.encode(text)
